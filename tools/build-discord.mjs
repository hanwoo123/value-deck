import {build} from 'esbuild';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const target=new URL('../supabase/trade-discord-dashboard.js',import.meta.url);
const result=await build({absWorkingDir:root,entryPoints:['supabase/functions/trade-discord/index.ts'],bundle:true,platform:'neutral',format:'esm',target:'es2022',write:false,legalComments:'none',banner:{js:'// Generated by npm run build:discord. Public code only; credentials are read from Supabase Secrets.\n// Paste the ENTIRE file into the Supabase Edge Function editor; name the function trade-discord.'}});
const text=result.outputFiles[0].text;
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==text)throw new Error('Discord dashboard file is stale. Run npm run build:discord.');}
else writeFileSync(target,text);
